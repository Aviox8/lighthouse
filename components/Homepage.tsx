"use client";

import { useCallback, useEffect, useRef, useState } from "react";
import { Search } from "lucide-react";
import SmoothButton from "@/components/smoothui/smooth-button";
import { Input } from "@/components/smoothui/input";
import Navbar from "@/components/Navbar";
import Footer from "@/components/Footer";
import CTA from "@/components/CTA";

/** Example queries must match the real grammar — radius is in kilometres. */
const EXAMPLE_QUERIES = [
  { label: "cell towers", query: "cell towers in Berlin radius:40" },
  { label: "data centers", query: "data centers near:London radius:60" },
  { label: "wind farms", query: "wind farms near Copenhagen radius:120" },
  { label: "substations", query: "type:substation in New York radius:80" },
  { label: "ports", query: "type:port near:Rotterdam radius:70" },
  { label: "hospitals", query: "type:hospital in mumbai" },
];

const FEATURES = [
  {
    title: "230+ asset types",
    body: "Telecom towers, data centers, power plants, substations, ports, hospitals, prisons — mapped onto OpenStreetMap tag filters across 30+ categories.",
    index: "01",
  },
  {
    title: "Compact query language",
    body: "Scope searches by asset type, operator, region, country, place, and radius — in plain language or structured tokens. No Overpass QL to wrangle.",
    index: "02",
  },
  {
    title: "Aggregate AI summaries",
    body: "Optional per-search summaries receive counts, never individual assets, and are always labeled with their provider. Locally generated by default.",
    index: "03",
  },
];

const QUERY_TOKENS = [
  { token: "type:", meaning: "Asset type key", example: "type:data_center" },
  { token: "operator:", meaning: "Operator / owner", example: "operator:google" },
  { token: "region:", meaning: "State / region", example: "region:california" },
  { token: "country:", meaning: "Country", example: "country:france" },
  { token: "near:", meaning: "Proximity anchor", example: "near:copenhagen" },
  { token: "radius:", meaning: "Radius in km (max 500)", example: "radius:80" },
];

const STRIP_ITEMS = [
  { label: "OpenStreetMap (ODbL)", href: "https://www.openstreetmap.org/copyright" },
  { label: "Overpass API", href: "https://wiki.openstreetmap.org/wiki/Overpass_API" },
  { label: "Nominatim", href: "https://nominatim.openstreetmap.org/" },
  { label: "MIT License", href: "/license" },
];

export interface HomepageProps {
  onSearch: (query: string) => void;
  loading: boolean;
}

export default function Homepage({ onSearch, loading }: HomepageProps) {
  const [query, setQuery] = useState("");
  const inputRef = useRef<HTMLInputElement>(null);

  const handleSubmit = useCallback(
    (e: React.FormEvent) => {
      e.preventDefault();
      const q = query.trim();
      if (q) onSearch(q);
    },
    [query, onSearch],
  );

  const handleExample = useCallback(
    (q: string) => {
      setQuery(q);
      onSearch(q);
    },
    [onSearch],
  );

  // "/" and ⌘K focus the hero search — the visible "/" chip is truthful.
  useEffect(() => {
    const handleKeyDown = (event: KeyboardEvent) => {
      const target = event.target as HTMLElement | null;
      const isTyping =
        target &&
        (target.tagName === "INPUT" ||
          target.tagName === "TEXTAREA" ||
          target.isContentEditable);
      const isSlash = event.key === "/" && !isTyping;
      const isCmdK =
        (event.metaKey || event.ctrlKey) &&
        event.key.toLowerCase() === "k" &&
        target !== inputRef.current;
      if (isSlash || isCmdK) {
        event.preventDefault();
        inputRef.current?.focus();
      }
    };
    window.addEventListener("keydown", handleKeyDown);
    return () => window.removeEventListener("keydown", handleKeyDown);
  }, []);

  return (
    <div className="home" aria-label="Lighthouse">
      <Navbar />

      <div className="home-hero">
        <div className="home-hero-inner">
          <div className="home-copy">
            <div className="home-eyebrow">
              <span className="home-eyebrow-index">01</span>
              <span className="home-dot" aria-hidden="true" />
              OPENSTREETMAP · INFRASTRUCTURE COMMAND
            </div>
            <h1 className="home-title">
              Map real-world infrastructure.
              <br />
              <span className="home-accent">From OpenStreetMap.</span>
            </h1>
            <p className="home-subtitle">
              Lighthouse queries 230+ asset types from OpenStreetMap — telecom
              towers, data centers, power plants, ports, hospitals — with a
              compact query language and optional aggregate summaries. Free,
              open source, no accounts.
            </p>

            <div className="home-command">
              <form onSubmit={handleSubmit} className="search-container">
                <div className="search-input-wrapper">
                  <Search className="search-icon" size={16} strokeWidth={2} />
                  <Input
                    ref={inputRef}
                    className="home-search-input"
                    placeholder="e.g. cell towers in Berlin radius:40"
                    value={query}
                    onChange={(e) => setQuery(e.target.value)}
                    disabled={loading}
                    autoComplete="off"
                    spellCheck={false}
                    name="query"
                    aria-label="Search query"
                  />
                  <SmoothButton
                    type="submit"
                    variant="solid"
                    color="accent"
                    size="sm"
                    disabled={loading}
                  >
                    <svg
                      viewBox="0 0 20 20"
                      fill="none"
                      stroke="currentColor"
                      strokeWidth="2"
                      strokeLinecap="round"
                      strokeLinejoin="round"
                      className="size-4"
                      aria-hidden="true"
                    >
                      <circle cx="10" cy="10" r="7" />
                      <line x1="16" y1="16" x2="18" y2="18" />
                    </svg>
                    Search
                  </SmoothButton>
                  {loading && (
                    <div className="search-spinner" aria-hidden="true" />
                  )}
                </div>
                {loading ? null : (
                  <div className="search-kbd" aria-hidden="true">
                    /
                  </div>
                )}
              </form>

              <div className="home-examples">
                <span className="home-examples-label">Try:</span>
                {EXAMPLE_QUERIES.map((example) => (
                  <button
                    key={example.query}
                    type="button"
                    className="home-chip"
                    onClick={() => handleExample(example.query)}
                    disabled={loading}
                    title={example.query}
                  >
                    <code>{example.label}</code>
                  </button>
                ))}
              </div>

              <div className="home-handoff">
                <a href="/docs">Read the documentation</a>
                <a href="/types">Browse asset types</a>
                <a
                  href="https://github.com/Aviox8/lighthouse"
                  target="_blank"
                  rel="noopener noreferrer"
                >
                  Source &amp; issues
                </a>
              </div>
            </div>
          </div>

          <aside className="home-console" aria-label="System readout">
            <h2 className="home-console-heading">System readout</h2>
            <dl className="home-readout">
              <div>
                <dt>Asset types</dt>
                <dd>230+</dd>
              </div>
              <div>
                <dt>Data source</dt>
                <dd>OSM · ODbL</dd>
              </div>
              <div>
                <dt>License</dt>
                <dd>MIT</dd>
              </div>
              <div>
                <dt>Accounts</dt>
                <dd>None</dd>
              </div>
              <div>
                <dt>AI summaries</dt>
                <dd>Aggregate-only</dd>
              </div>
              <div>
                <dt>Result cap</dt>
                <dd>5,000</dd>
              </div>
            </dl>
          </aside>
        </div>
      </div>

      <div className="home-strip" aria-label="Open data sources">
        {STRIP_ITEMS.map((item, i) => (
          <span
            className={`home-strip-item${i === STRIP_ITEMS.length - 1 ? " home-strip-no-rule" : ""}`}
            key={item.label}
          >
            <a href={item.href}>{item.label}</a>
          </span>
        ))}
      </div>

      <section className="home-section" aria-label="What it does">
        <div className="home-section-inner">
          <h2 className="home-section-title">What it does</h2>
          <div className="home-features-grid">
            {FEATURES.map((feature) => (
              <article key={feature.title} className="home-feature">
                <span className="home-feature-index">{feature.index} /</span>
                <h3 className="home-feature-title">{feature.title}</h3>
                <p className="home-feature-body">{feature.body}</p>
              </article>
            ))}
          </div>
        </div>
      </section>

      <section className="home-section" aria-label="Query language">
        <div className="home-section-inner">
          <h2 className="home-section-title">The query language</h2>
          <div className="home-queries-grid">
            <table className="landing-table">
              <thead>
                <tr>
                  <th scope="col">Token</th>
                  <th scope="col">Meaning</th>
                </tr>
              </thead>
              <tbody>
                {QUERY_TOKENS.map((token) => (
                  <tr key={token.token}>
                    <td>
                      <code>{token.token}</code>
                    </td>
                    <td>
                      {token.meaning} — <code>{token.example}</code>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
            <div>
              <p className="home-prose">
                Natural language works too — &ldquo;telecom towers in
                Karnataka&rdquo;, &ldquo;wind farms near Copenhagen&rdquo;.
                Structured tokens are exact: combine them in any order.
              </p>
              <p className="home-prose">
                Every query needs a type or an operator and a geographic scope.
                The searchable set is cataloged on the{" "}
                <a className="home-inline-link" href="/types">
                  asset types page
                </a>
                .
              </p>
            </div>
          </div>
        </div>
      </section>

      <section className="home-section cta" aria-label="Get started">
        <div className="cta-inner">
          <div className="cta-copy">
            <h2 className="cta-title">Ready to search?</h2>
            <p className="cta-sub">
              No account, no install. Type a query — the workbench opens with
              the map, results, filters, and an optional aggregate summary.
            </p>
          </div>
          <div className="cta-action">
            <CTA onSearch={onSearch} loading={loading} />
          </div>
        </div>
      </section>

      <Footer />
    </div>
  );
}
